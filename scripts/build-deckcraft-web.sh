# Build DeckCraft for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-deckcraft-web.sh [DECKCRAFT_CHECKOUT]
#
#   DECKCRAFT_CHECKOUT  an existing clone of github.com/storytold/deckcraft. Without it the
#                       script clones DECKCRAFT_REF into build/deckcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in DeckCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   DECKCRAFT_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
#   CRAFT_FONTS_DIR  a clone of storytold/craft-fonts, to embed the shared Japanese fonts
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DECKCRAFT_REF="${DECKCRAFT_REF:-688c7ef592c901ca4541c25e210c1b302e4dc066}"
SRC="${1:-$APP_DIR/build/deckcraft}"
PATCH="$APP_DIR/patches/deckcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/deckcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$DECKCRAFT_REF"
fi

if grep -rq 'deckcraft:ready' "$SRC/apps/deckcraft-web/src"; then
	echo "DeckCraft has the embedding bridge"
elif [ -s "$PATCH" ]; then
	git -C "$SRC" apply "$PATCH"
else
	echo "error: this DeckCraft has no embedding bridge, and there is no patch to add it" >&2
	exit 1
fi

cargo_args=(build --profile release -p deckcraft-web --target wasm32-unknown-unknown)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/deckcraft-web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
OUT_NAME=deckcraft-web
wasm-bindgen --target web --weak-refs --no-typescript --out-dir "$STAGE" --out-name "$OUT_NAME" "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/${OUT_NAME}_bg.wasm" -o "$STAGE/${OUT_NAME}_bg.opt.wasm"
	mv "$STAGE/${OUT_NAME}_bg.opt.wasm" "$STAGE/${OUT_NAME}_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

mkdir -p "$OUT"
hash() { sha256sum "$1" | cut -c1-16; }
# Content-hashed names: Nextcloud lets browsers cache app assets for months.
DEST="$OUT"
JS_NAME="deckcraft-web-$(hash "$STAGE/$OUT_NAME.js").js"
WASM_NAME="deckcraft-web-$(hash "$STAGE/${OUT_NAME}_bg.wasm").wasm"
rm -f "$OUT"/deckcraft-web-*.js "$OUT"/deckcraft-web-*.wasm
cp "$STAGE/$OUT_NAME.js" "$DEST/$JS_NAME"
cp "$STAGE/${OUT_NAME}_bg.wasm" "$DEST/$WASM_NAME"
# JavaScript the Rust code brings along (`#[wasm_bindgen(module = …)]`), imported by the glue.
rm -rf "$DEST/snippets"
if [ -d "$STAGE/snippets" ]; then cp -R "$STAGE/snippets" "$DEST/snippets"; fi

# DeckCraft's licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md ASSETS.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/DECKCRAFT-$f"; fi
done

cat > "$DEST/boot.js" <<BOOT
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts DeckCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-deckcraft-web.sh from DeckCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('DeckCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'deckcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	const app = await import('./$JS_NAME')
	await app.default({ module_or_path: new URL('./$WASM_NAME', import.meta.url) })

} catch (error) {
	reportFailure(error)
}
BOOT

echo "DeckCraft web build:"
ls -lh "$OUT"
